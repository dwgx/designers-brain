def s81b_from_card(lines):
    """卡内 §8.1b 节（若存在）——从 '## §8.1b' 起、至下一个 '## ' 级标题前（原样）。"""
    i = None
    for idx, l in enumerate(lines):
        if l.startswith("## §8.1b"):
            i = idx
            break
    if i is None:
        return None
    j = len(lines)
    for idx in range(i + 1, len(lines)):
        if lines[idx].startswith("## "):
            j = idx
            break
    return "\n".join(trim(lines[i:j]))


